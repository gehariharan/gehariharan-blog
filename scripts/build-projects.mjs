const ABOUT_START = "<!-- apps:start (generated by scripts/build-projects.mjs) -->";
const ABOUT_END = "<!-- apps:end -->";

function indent(html, tabs) {
	const pad = "\t".repeat(tabs);
	return html
		.split("\n")
		.map((line) => (line ? pad + line : line))
		.join("\n");
}

export function renderProjectCard(project) {
	const statusClass = project.status === "soon" ? "project-status soon" : "project-status";
	return `<a class="project-card" href="${escapeAttr(project.url)}" target="_blank" rel="noopener noreferrer">
	<span class="project-logo ${escapeAttr(project.logoFit)}"><img src="${escapeAttr(project.logo)}" alt="" /></span>
	<h3 class="project-name">${escapeHtml(project.name)}</h3>
	<p class="project-line">${escapeHtml(project.line)}</p>
	<span class="project-meta"><span class="${statusClass}">${escapeHtml(project.statusText)}</span><span class="project-link">${escapeHtml(project.linkText)} &nearr;</span></span>
</a>`;
}

function renderGrid(projects) {
	return `<div class="project-grid">
${indent(projects.map(renderProjectCard).join("\n"), 1)}
</div>`;
}

