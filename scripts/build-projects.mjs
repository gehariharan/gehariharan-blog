export function renderAboutApps(groups = PROJECT_GROUPS) {
	const projects = groups.filter((group) => group.onAbout).flatMap((group) => group.projects);
	return `<section class="about-apps" aria-labelledby="about-apps-title">
	<h2 id="about-apps-title">Apps I’ve built</h2>
${indent(renderGrid(projects), 1)}
	<a class="about-apps-more" href="/projects/">All projects &rarr;</a>
</section>`;
}

// Replaces everything between the About page's apps markers, keeping the markers.
export function updateAboutPage(html, groups = PROJECT_GROUPS) {
	const start = html.indexOf(ABOUT_START);
	const end = html.indexOf(ABOUT_END);
	if (start === -1 || end === -1 || end < start) {
		throw new Error(`About page is missing the apps markers: ${ABOUT_START} ... ${ABOUT_END}`);
	}
	const lineStart = html.lastIndexOf("\n", start) + 1;
	const markerIndent = html.slice(lineStart, start);
	const tabs = markerIndent.length;
	return `${html.slice(0, start + ABOUT_START.length)}\n${indent(renderAboutApps(groups), tabs)}\n${markerIndent}${html.slice(end)}`;
}

export function buildProjects() {
	writeFileSync(PROJECTS_PAGE, renderProjectsPage());
	writeFileSync(ABOUT_PAGE, updateAboutPage(readFileSync(ABOUT_PAGE, "utf-8")));
	const count = PROJECT_GROUPS.reduce((total, group) => total + group.projects.length, 0);
	console.log(`Built public/projects/ (${count} projects) and the About page apps section.`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	buildProjects();
}
